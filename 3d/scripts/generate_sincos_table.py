#!/usr/bin/env python3
"""Generate coarse/fine forward and inverse tables for the trig APIs."""

from __future__ import annotations

import argparse
import hashlib
import struct
from decimal import Decimal, ROUND_HALF_UP, getcontext
from pathlib import Path


getcontext().prec = 90
PI = Decimal(
    "3.141592653589793238462643383279502884197169399375105820974944"
    "5923078164062862089986280348253421170679"
)
EXPECTED_SHA256 = "98a6464b9f25bd589351585972014e17e15b23f5f364d2a9d630e4205630d864"


def sin_decimal(value: Decimal) -> Decimal:
    term = value
    total = value
    square = value * value
    n = 1
    while True:
        term *= -square / Decimal((2 * n) * (2 * n + 1))
        updated = total + term
        if updated == total:
            return total
        total = updated
        n += 1


def atan_decimal(value: Decimal) -> Decimal:
    """Return atan(value) without depending on platform libm results."""

    if value < 0:
        return -atan_decimal(-value)
    if value > Decimal("0.5"):
        return PI / 4 + atan_decimal((value - 1) / (value + 1))

    square = value * value
    term = value
    total = value
    denominator = 1
    while True:
        term *= -square
        denominator += 2
        updated = total + term / Decimal(denominator)
        if updated == total:
            return total
        total = updated


def build_table() -> tuple[list[int], list[int]]:
    quarter = []
    for index in range(65):
        angle = PI * Decimal(index) / Decimal(128)
        scaled = sin_decimal(angle) * Decimal(32767)
        quarter.append(int(scaled.to_integral_value(rounding=ROUND_HALF_UP)))

    sine = [0] * 256
    for index, value in enumerate(quarter):
        sine[index] = value
        sine[(128 - index) & 255] = value
        sine[(128 + index) & 255] = -value
        sine[-index & 255] = -value
    cosine = [sine[(index + 64) & 255] for index in range(256)]

    assert min(sine) == -32767 and max(sine) == 32767
    assert (sine[0], sine[64], sine[128], sine[192]) == (
        0, 32767, 0, -32767,
    )
    assert all(cosine[i] == sine[(i + 64) & 255] for i in range(256))
    assert all(sine[-i & 255] == -sine[i] for i in range(256))
    return sine, cosine


def build_fine_atan_table() -> list[int]:
    """Build first-octant atan nodes for a Q15 min/max ratio."""

    table = []
    for index in range(65):
        ratio = Decimal(index) / Decimal(64)
        scaled = atan_decimal(ratio) * Decimal(32768) / (2 * PI)
        table.append(
            int(scaled.to_integral_value(rounding=ROUND_HALF_UP))
        )
    assert table[0] == 0
    assert table[-1] == 4096
    assert all(
        0 < table[index + 1] - table[index] <= 82
        for index in range(64)
    )
    return table


def build_inverse_tables(
    sine: list[int],
    cosine: list[int],
) -> tuple[list[tuple[int, int]], list[int]]:
    atan2_boundaries = [
        (
            cosine[index] - cosine[index + 1],
            sine[index + 1] - sine[index],
        )
        for index in range(32)
    ]
    asin_thresholds = [
        (sine[index] + sine[index + 1]) // 2 + 1
        for index in range(64)
    ]

    assert len(atan2_boundaries) == 32
    assert all(
        (dx, dy) == (
            cosine[index] - cosine[index + 1],
            sine[index + 1] - sine[index],
        )
        for index, (dx, dy) in enumerate(atan2_boundaries)
    )
    assert all(0 < dx <= 32767 and 0 < dy <= 32767
               for dx, dy in atan2_boundaries)
    assert all(
        sine[index] * dy <= cosine[index] * dx
        and sine[index + 1] * dy > cosine[index + 1] * dx
        for index, (dx, dy) in enumerate(atan2_boundaries)
    )

    assert len(asin_thresholds) == 64
    assert all(
        threshold == (sine[index] + sine[index + 1]) // 2 + 1
        for index, threshold in enumerate(asin_thresholds)
    )
    assert all(
        0 < asin_thresholds[index] < asin_thresholds[index + 1] <= 32767
        for index in range(63)
    )
    assert all(
        abs((threshold - 1) - sine[index])
        <= abs((threshold - 1) - sine[index + 1])
        and abs(threshold - sine[index + 1])
        < abs(threshold - sine[index])
        for index, threshold in enumerate(asin_thresholds)
    )
    return atan2_boundaries, asin_thresholds


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("src/asm/agon/3d_sincos_table.inc"),
    )
    args = parser.parse_args()

    sine, cosine = build_table()
    fine_atan = build_fine_atan_table()
    atan2_boundaries, asin_thresholds = build_inverse_tables(sine, cosine)
    packed = b"".join(
        struct.pack("<hh", sine[index], cosine[index])
        for index in range(256)
    )
    digest = hashlib.sha256(packed).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(f"unexpected table SHA-256: {digest}")

    lines = [
        "; Generated by scripts/generate_sincos_table.py; do not hand-edit.",
        f"; Packed little-endian SHA-256: {digest}",
        "p3d_sincos_q15:",
    ]
    lines.extend(
        f"    dw {sine[index]:6d},{cosine[index]:6d} ; {index:3d}"
        for index in range(256)
    )
    lines.extend([
        f"    dw {sine[0]:6d},{cosine[0]:6d} ; 256 interpolation sentinel",
        "",
        "; First-octant atan nodes for a Q15 min/max ratio.",
        "; Linear interpolation uses the low nine ratio bits.",
        "p3d_atan_octant_fine_q15:",
    ])
    lines.extend(
        f"    dw {angle:6d} ; {index:2d}/64"
        for index, angle in enumerate(fine_atan)
    )
    lines.extend([
        "",
        "; First-octant atan2 nearest-bin boundaries.",
        "; Each entry is dx=cos[j]-cos[j+1], dy=sin[j+1]-sin[j].",
        "p3d_atan2_octant_boundaries_q15:",
    ])
    lines.extend(
        f"    dw {dx:6d},{dy:6d} ; {index:2d}"
        for index, (dx, dy) in enumerate(atan2_boundaries)
    )
    lines.extend([
        "",
        "; Positive-quadrant asin nearest-bin thresholds.",
        "; Each entry is floor((sin[j]+sin[j+1])/2)+1.",
        "p3d_asin_thresholds_q15:",
    ])
    lines.extend(
        f"    dw {threshold:6d} ; {index:2d}"
        for index, threshold in enumerate(asin_thresholds)
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="ascii")
    fine_bytes = 4 + 2 * len(fine_atan)
    inverse_bytes = 4 * len(atan2_boundaries) + 2 * len(asin_thresholds)
    print(
        f"wrote {len(packed)} sine/cosine bytes and "
        f"{fine_bytes} fine interpolation bytes and "
        f"{inverse_bytes} coarse inverse bytes to {args.output}"
    )


if __name__ == "__main__":
    main()
